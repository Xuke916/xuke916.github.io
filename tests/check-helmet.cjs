const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {JSDOM}=require('jsdom'),root=path.resolve(__dirname,'../dist');
const dom=new JSDOM('<div class="hero-portrait"></div>',{runScripts:'outside-only'}),w=dom.window;
let pauses=0,resumes=0;
w.SVGSVGElement.prototype.pauseAnimations=()=>pauses++;
w.SVGSVGElement.prototype.unpauseAnimations=()=>resumes++;
w.eval(fs.readFileSync(path.join(root,'helmet-ink.js'),'utf8'));
const portrait=w.document.querySelector('div'),api=w.HelmetInk,ink=api.mount(portrait),svg=portrait.querySelector('svg');
assert.equal(api.mount(portrait),ink);assert.equal(svg.getAttribute('viewBox'),'0 0 1448 1086');
assert.equal(svg.dataset.structure,'current-photo-contours');
assert.equal(svg.querySelectorAll('.helmet-shell').length,1);assert.equal(svg.querySelectorAll('.helmet-guard').length,1);
assert.ok(svg.querySelectorAll('.helmet-details path').length>=20);
assert.ok(svg.querySelectorAll('path').length<40,'detailed photo contours replace thousands of unrelated mesh segments');
assert.equal(svg.querySelector('[stroke-dasharray]'),null,'old perimeter animation is gone');
const reveal=svg.querySelector('clipPath rect'),anim=reveal.querySelector('animate');
assert.equal(reveal.getAttribute('y'),'335','reveal begins just above the current helmet crown');
assert.equal(anim.getAttribute('attributeName'),'height');
assert.equal(anim.getAttribute('values'),'0;0;560;560','the window opens downward and holds instead of reversing');
assert.equal(anim.getAttribute('dur'),'4.6s');
assert.equal(svg.querySelector('.helmet-drawing>animate').getAttribute('attributeName'),'opacity','drawing fades before scan resets');
assert.equal(svg.querySelector('g').getAttribute('fill'),'none');
assert.match(api.outline.shell,/638 349/,'crown matches the replacement photograph, below the old outline');
assert.ok(fs.existsSync(path.join(root,'assets/hero-helmet-v2.png')));
ink.setActive(false);ink.setActive(false);assert.equal(pauses,1);ink.setActive(true);assert.equal(resumes,1);
ink.setThumbnail(.5);assert.ok(+svg.style.opacity>0&&+svg.style.opacity<.5);
ink.setThumbnail(1);assert.equal(svg.style.opacity,'0');ink.setThumbnail(0);assert.equal(svg.style.opacity,'1');
ink.remove();assert.equal(portrait.children.length,0);dom.window.close();
console.log('PASS current-photo helmet contours, vents/guard details, downward reveal, reset fade, bounded complexity and lifecycle pause');
